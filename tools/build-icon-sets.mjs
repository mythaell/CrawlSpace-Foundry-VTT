/**
 * Foundry install → src/import/icon-sets.ts: for each folder an icon rule in src/import/icons.ts names,
 * up to eight of that folder's core icons, spread across it. Also checks that every single icon a rule
 * names exists in this Foundry version.
 *
 *   node tools/build-icon-sets.mjs ["C:/Program Files/Foundry Virtual Tabletop"]
 */
import fs from 'node:fs'
import path from 'node:path'
import { ROOT } from './lib.mjs'

const install = process.argv[2] ?? process.env.FOUNDRY_INSTALL ?? 'C:/Program Files/Foundry Virtual Tabletop'
const iconRoot = path.join(install, 'resources', 'app', 'public')
if (!fs.existsSync(path.join(iconRoot, 'icons'))) throw new Error(`No Foundry icons under ${iconRoot}. Pass the Foundry install folder.`)

const all = []
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (entry.name.endsWith('.webp')) all.push(path.relative(path.join(iconRoot, 'icons'), full).replaceAll('\\', '/').replace(/\.webp$/, ''))
  }
}
walk(path.join(iconRoot, 'icons'))
all.sort()

const source = fs.readFileSync(path.join(ROOT, 'src', 'import', 'icons.ts'), 'utf8')
const named = [...source.matchAll(/'((?:magic|skills|weapons|equipment|commodities|consumables|containers|creatures|environment|sundries|tools)\/[a-z0-9/-]*)'/g)].map((m) => m[1])
const folders = [...new Set(named.filter((icon) => /[/-]$/.test(icon)))].sort()
const missing = named.filter((icon) => !/[/-]$/.test(icon) && !all.includes(icon))

const PER_FOLDER = 8
const sets = {}
for (const folder of folders) {
  const hits = all.filter((icon) => icon.startsWith(folder))
  if (!hits.length) {
    missing.push(folder)
    continue
  }
  const step = hits.length / Math.min(PER_FOLDER, hits.length)
  sets[folder] = Array.from({ length: Math.min(PER_FOLDER, hits.length) }, (_, i) => hits[Math.floor(i * step)].slice(folder.length))
}

const lines = Object.entries(sets).map(([folder, names]) => `  '${folder}': [${names.map((name) => `'${name}'`).join(', ')}],`)
fs.writeFileSync(
  path.join(ROOT, 'src', 'import', 'icon-sets.ts'),
  `// Generated by tools/build-icon-sets.mjs from Foundry's core icons. Do not edit by hand.\nexport const ICON_SETS: Record<string, string[]> = {\n${lines.join('\n')}\n}\n`,
)
console.log(`${folders.length} folders, ${Object.values(sets).flat().length} icons written to src/import/icon-sets.ts`)
if (missing.length) {
  console.error('Not in this Foundry version:', [...new Set(missing)].join(', '))
  process.exitCode = 1
}
