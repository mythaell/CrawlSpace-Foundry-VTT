const SLOT_FOLDERS: Record<string, string> = {
  head: 'equipment/head/',
  torso: 'equipment/chest/',
  arms: 'equipment/wrist/',
  hands: 'equipment/hand/',
  legs: 'equipment/leg/',
  feet: 'equipment/feet/',
  accessory: 'equipment/neck/',
}
const FALLBACKS: Record<string, string> = {
  spell: 'magic/symbols/',
  consumable: 'consumables/potions/',
  tattoo: 'tools/scribal/ink-quill-pink',
  loot: 'containers/bags/',
}

const hash = (text: string) => [...text].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0, 7)

function resolve(icon: string, name: string) {
  if (!/[/-]$/.test(icon)) return `icons/${icon}.webp`
  const set = ICON_SETS[icon]
  return set?.length ? `icons/${icon}${set[hash(name) % set.length]}.webp` : null
}

/** A core icon for this skill, spell or item, or null when nothing fits (the caller keeps its default). */
export function iconFor(type: string, name: string, system: Record<string, any> = {}): string | null {
  const rule = ICON_RULES.find(([pattern, , types]) => (!types || types.includes(type)) && pattern.test(name))
  if (rule) return resolve(rule[1], name)
  if (type === 'weapon') return resolve(system.weaponType === 'ranged' ? 'weapons/bows/' : 'weapons/swords/', name)
  if (type === 'equipment') return resolve(system.isShield ? 'equipment/shield/' : (SLOT_FOLDERS[system.slot] ?? 'equipment/neck/'), name)
  return FALLBACKS[type] ? resolve(FALLBACKS[type], name) : null
}
